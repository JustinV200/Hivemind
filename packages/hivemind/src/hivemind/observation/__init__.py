"""Serve the Observation Hive's read side: its read models, its aggregated screens and its metrics.

The read models (``hivemind.observation.views``) are what every Observation Hive view renders
(codingrules 8.11): Cells, Wardens, tasks, the Forage split, thoughts, the trail, providers and
the live views' frames. The aggregated screens (``hivemind.observation.api``) join several of them
into the models the summary strip, the Fleet list, a Cell page, an Attendant view, the Thoughts
page, the Capping view and the Cost view render, each with a pure builder over records the
Entrance gathers. The metrics (``hivemind.observation.metrics``) are one snapshot of the Hive's
figures and its Prometheus text. The Entrance answers its read routes and streams with these and
publishes them in the OpenAPI document the front end's types are generated from; it imports them
from this face only. The front end that renders them lives separately, in
packages/observation-web.

Fits into the Hive:
    Layer 7 (edges: HTTP, terminal, dashboard). Used by ``hivemind.entrance`` (its routes, read
    side and live views), the one same-layer import ADR-0040 lists; never imports the Entrance.
    Calls into the Hive's record types (Brood Chamber, Cells, Forage, memory, the trail, the
    Queen's ledger and mode) and pydantic.

Key invariants:
    - This file holds re-exports and ``__all__`` only.
    - Nothing in this package writes or reads a store: every view is a read model and every
      builder is pure (codingrules 8.11's one write path is the Queen's inbox, which the Entrance
      owns).

See Also:
    - .claude/codingrules.md 8.11 for the views these models serve.
    - .claude/roadmap.md step 12.1 for the read API and metrics.

Public API:
    - Every name ``hivemind.observation.views`` exports; its face groups them by view. The Honey
      browser's lesser models stay behind it: this face carries the five the Entrance's routes
      declare (HoneyFolderView, HoneyItemView, HoneySearchPage, HoneyTreeQuery, HoneySearchQuery),
      each with its own constructor, so the file stays under the size limit.
    - Every name ``hivemind.observation.api`` exports: the screens' models and builders.
    - MetricsSnapshot, MetricsInputs, metrics_snapshot, render_snapshot, METRICS_CONTENT_TYPE and
      the snapshot's count models: the metrics (``hivemind.observation.metrics``).
"""

